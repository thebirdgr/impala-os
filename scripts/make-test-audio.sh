#!/usr/bin/env bash
# Generate a small, legally clean (CC0, generated here) test library of
# tagged sine tones with cover art, plus one deliberately broken file.
# Run ON THE PI (needs ffmpeg, already present on Raspberry Pi OS):
#
#   scripts/make-test-audio.sh [/srv/music] [--playlists]
#
# --playlists also rescans MPD and saves the "Favourites" and "Road Trip"
# playlists via mpc.
set -euo pipefail

root="${1:-/srv/music}"
out="$root/impala-test"
font=/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf
command -v ffmpeg >/dev/null || { echo "ffmpeg not found" >&2; exit 1; }

ff() { ffmpeg -hide_banner -loglevel error -y "$@"; }

cover() { # out.jpg "Text" color0 color1
    local text=$2
    local draw=""
    [[ -f $font ]] && draw=",drawtext=fontfile=$font:text='$text':fontcolor=white:fontsize=46:x=(w-text_w)/2:y=(h-text_h)/2:box=1:boxcolor=black@0.35:boxborderw=18"
    ff -f lavfi -i "gradients=s=500x500:c0=$3:c1=$4:x0=0:y0=0:x1=500:y1=500:duration=1:rate=1$draw" -frames:v 1 "$1"
}

tone() { # out title artist album track freq secs [cover-to-embed]
    local o=$1 title=$2 artist=$3 album=$4 track=$5 freq=$6 secs=$7 embed=${8:-}
    local fade=$((secs - 1))
    local src=(-f lavfi -i "sine=frequency=$freq:duration=$secs:sample_rate=44100")
    local meta=(-metadata "title=$title" -metadata "artist=$artist" -metadata "album=$album"
        -metadata "track=$track" -metadata "date=2026" -metadata "comment=Generated test tone (CC0)")
    local af=(-af "volume=0.25,afade=t=in:d=0.5,afade=t=out:st=$fade:d=1" -ac 2)
    if [[ -n $embed ]]; then
        ff "${src[@]}" -i "$embed" -map 0:a -map 1:v "${af[@]}" -c:v mjpeg -disposition:v attached_pic \
            -metadata:s:v "comment=Cover (front)" "${meta[@]}" "$o"
    else
        ff "${src[@]}" "${af[@]}" "${meta[@]}" "$o"
    fi
}

echo "writing test library to $out"
mkdir -p "$out/signal-path" "$out/low-frequencies" "$out/mixed" "$out/broken"

# Album 1: folder cover.jpg (MPD `albumart`).
cover "$out/signal-path/cover.jpg" "Signal Path" 0x1d3557 0xf0a020
tone "$out/signal-path/01-highway-hum.flac"       "Highway Hum"        "The Test Tones" "Signal Path" 1 220 40
tone "$out/signal-path/02-night-drive.flac"       "Night Drive (A440)" "The Test Tones" "Signal Path" 2 440 35
tone "$out/signal-path/03-rest-stop.flac"         "Rest Stop"          "The Test Tones" "Signal Path" 3 330 45

# Album 2: cover embedded in the files (MPD `readpicture`).
tmpcover="$(mktemp --suffix=.jpg)"
cover "$tmpcover" "Low Frequencies" 0x3b1f4f 0x4fc3a1
tone "$out/low-frequencies/01-odometer.flac"      "Odometer Rollover"  "Sine Wave Society" "Low Frequencies" 1 110 30 "$tmpcover"
tone "$out/low-frequencies/02-cruise-control.flac" "Cruise Control"    "Sine Wave Society" "Low Frequencies" 2 165 30 "$tmpcover"
rm -f "$tmpcover"

# Mixed formats, no cover at all (placeholder tile).
ff -f lavfi -i "sine=frequency=523.25:duration=25:sample_rate=44100" -ac 2 -af "volume=0.25" \
    -c:a libmp3lame -q:a 4 -metadata "title=C5 in MP3" -metadata "artist=Format Check" -metadata "album=Mixed" \
    "$out/mixed/c5.mp3"
ff -f lavfi -i "sine=frequency=392:duration=25:sample_rate=44100" -ac 2 -af "volume=0.25" \
    -c:a libvorbis -q:a 3 -metadata "title=G4 in Ogg" -metadata "artist=Format Check" -metadata "album=Mixed" \
    "$out/mixed/g4.ogg"

# A corrupt file: MPD must report an error, the app must show it, nobody crashes.
head -c 4096 /dev/urandom > "$out/broken/not-really-audio.flac"

cat > "$out/LICENSE.txt" <<'EOF'
All audio and images in this folder were generated by scripts/make-test-audio.sh
(sine tones and gradients via ffmpeg). Dedicated to the public domain (CC0 1.0).
EOF
chmod -R a+rX "$out"
ls -lR "$out" | grep -E "\.(flac|mp3|ogg|jpg)$" | awk '{print $5, $NF}'

if [[ " $* " == *" --playlists "* ]]; then
    echo "rescanning MPD and saving playlists"
    mpc -q -w update
    mpc -q clear
    mpc -q add impala-test/signal-path/02-night-drive.flac impala-test/low-frequencies/01-odometer.flac impala-test/mixed/c5.mp3
    mpc -q rm Favourites 2>/dev/null || true
    mpc -q save Favourites
    mpc -q clear
    mpc -q add impala-test/low-frequencies/02-cruise-control.flac impala-test/signal-path/01-highway-hum.flac impala-test/mixed/g4.ogg impala-test/signal-path/03-rest-stop.flac
    mpc -q rm "Road Trip" 2>/dev/null || true
    mpc -q save "Road Trip"
    mpc -q clear
    mpc -q add impala-test
    mpc lsplaylists
    echo "library: $(mpc listall | wc -l) files"
fi
